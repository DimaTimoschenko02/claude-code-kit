function project(t, name = 'pgvector') {
  const root = mkdtempSync(join(tmpdir(), 'ci runner space '));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const directory = join(root, 'infra', 'ci-runner');
  mkdirSync(directory, { recursive: true });
  const config = fixture(name);
  const save = () => writeFileSync(join(directory, 'runner.json'), JSON.stringify(config));
  save();
  return { root, directory, config, save };
}

function imageSemantics(contents) {
  const lines = contents.replace(/^\s*#.*$/gm, '').replace(/\\\r?\n/g, ' ').split(/\r?\n/).filter((l) => l.trim());
  const result = { args: {}, environment: {}, runs: [] };
  for (const line of lines) {
    const [, kind, body] = /^(\w+)\s+(.+)$/.exec(line);
    const value = body.trim().replace(/\s+/g, ' ');
    if (kind === 'ARG' || kind === 'ENV') {
      const at = value.indexOf('=');
      result[kind === 'ARG' ? 'args' : 'environment'][value.slice(0, at)] = value.slice(at + 1);
    } else if (kind === 'RUN') {
      result.runs.push(value.replace(/(apt-get install -y --no-install-recommends )(.+?)(?= &&)/,
        (_, prefix, packages) => prefix + packages.split(' ').sort().join(' ')));
    } else result[kind.toLowerCase()] = kind === 'ENTRYPOINT' ? JSON.parse(value) : value;
  }
  return result;
}

for (const name of ['playwright', 'two-runners']) {
  test(`${name}: Compose matches the reference model, except explicitly enumerated upgrades`, (t) => {
    const p = project(t, name);
    render(p.root);
    const expected = JSON.parse(read(join(FIXTURES, 'references', name), 'compose.semantic.json'));
    for (const key of Object.keys(expected.volumes)) expected.volumes[key] ??= {};
    if (name === 'two-runners') upgradeTwoRunnerCompose(expected, p.config);
    assert.deepEqual(yaml(read(p.directory, 'compose.yaml')), expected);
  });

  test(`${name}: Dockerfile instructions match the reference, ignoring comments and argument/package order`, (t) => {
    const p = project(t, name);
    render(p.root);
    const expected = imageSemantics(read(join(FIXTURES, 'references', name), 'Dockerfile'));
    expected.entrypoint = ['/bin/bash', '/usr/local/bin/runner-entrypoint'];
    if (name === 'two-runners') upgradeTwoRunnerImage(expected);
    assert.deepEqual(imageSemantics(read(p.directory, 'Dockerfile')), expected);
  });

}

function upgradeTwoRunnerCompose(expected, config) {
  for (const service of Object.values(expected.services)) service.memswap_limit = service.mem_limit;
  expected.services.postgres.environment.PGDATA = '/var/lib/postgresql/ci-data';
  expected.services.postgres.logging = { driver: 'json-file', options: { 'max-size': '10m', 'max-file': '3' } };
  ['runner', 'runner-light'].forEach((name, index) => {
    Object.assign(expected.services[name].environment, { RUNNER_REPO_URL: `https://github.com/${config.repo}`,
      RUNNER_NAME: config.runners[index].name, RUNNER_LABELS: config.runners[index].labels.join(',') });
  });
}

function upgradeTwoRunnerImage(expected) {
  expected.args.DEBIAN_FRONTEND = 'noninteractive';
  expected.environment.LANG = 'C.UTF-8';
  expected.runs[0] = expected.runs[0].replace(/(apt-get install -y --no-install-recommends )(.+?)(?= &&)/,
    (_, prefix, packages) => prefix + [...packages.split(' '), 'openssh-client'].sort().join(' '));
  expected.runs[2] = expected.runs[2].replace(' && chown', ' && rm -rf /var/lib/apt/lists/* && chown');
}

