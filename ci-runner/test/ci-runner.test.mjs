test('install uses safe local arguments and remote directory quoting; token is only the final stdin', (t) => {
  const p = project(t);
  p.config.dir = '/opt/ci runner space'; p.save(); render(p.root);
  const fake = fakeExecution();
  install(p.root, { run: fake.run, env: { CI_RUNNER_HOST: 'ci@override.invalid' } });
  assert.deepEqual(fake.calls.map((c) => c.command), ['gh', 'ssh', 'scp', 'gh', 'ssh']);
  assert.equal(fake.calls[1].args[1], "install -d -m 700 -- '/opt/ci runner space'");
  assert.ok(fake.calls[2].args.includes('./compose.yaml'));
  assert.equal(fake.calls[2].options.cwd, p.directory);
  assert.equal(fake.calls[2].args.at(-1), "ci@override.invalid:'/opt/ci runner space/'");
  assert.match(fake.calls.at(-1).args[1], /^cd '\/opt\/ci runner space' && RUNNER_TOKEN=\$\(cat\)/);
  assert.equal(fake.calls.at(-1).input, 'FAKE_REGISTRATION_TOKEN');
  assert.deepEqual(fake.calls.at(-1).options.stdio, ['pipe', 'ignore', 'ignore']);
  assert.ok(!JSON.stringify(fake.calls.map((c) => c.args)).includes('FAKE_REGISTRATION_TOKEN'));
  assert.ok(fake.calls.slice(0, -1).every((c) => c.input === undefined));
  assert.ok(fake.token.every((byte) => byte === 0), 'clear token buffer after use');
});

