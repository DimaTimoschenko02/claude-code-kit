test('install stops after every failing subprocess, rejects empty tokens, and clears tokens after SSH failure', (t) => {
  const p = project(t); render(p.root);
  for (let failure = 0; failure < 5; failure++) {
    const fake = fakeExecution(); let count = 0;
    assert.throws(() => install(p.root, { run: (...args) => {
      if (count++ === failure) throw new Error('simulated failure');
      return fake.run(...args);
    } }), /simulated failure/);
    assert.equal(count, failure + 1);
    if (failure === 4) assert.ok(fake.token.every((byte) => byte === 0));
  }
  for (const token of ['', 'bad\nresponse', 'null\n']) {
    const fake = fakeExecution();
    assert.throws(() => install(p.root, { run: (...args) => args[1].includes('POST') ? Buffer.from(token) : fake.run(...args) }), /invalid registration/);
    assert.equal(fake.calls.length, 3, 'no final SSH');
  }
});

test('runner entrypoint registers once, passes env values verbatim, and removes token before jobs', (t) => {
  const p = project(t); render(p.root);
  const home = join(p.root, 'fake-home'); mkdirSync(home);
  const script = read(p.directory, 'entrypoint.sh').replace('cd /home/runner/actions-runner', 'cd "$FAKE_HOME"');
  writeFileSync(join(home, 'entrypoint.sh'), script);
  writeFileSync(join(home, 'config.sh'), '#!/bin/bash\nprintf "%s\\n" "$@" > config-args\ntouch .runner\n', { mode: 0o755 });
  writeFileSync(join(home, 'run.sh'), '#!/bin/bash\nprintf "token=%s\\n" "${RUNNER_TOKEN-unset}"\n', { mode: 0o755 });
  const env = { ...process.env, FAKE_HOME: home.replaceAll('\\', '/'), RUNNER_TOKEN: 'FAKE_TOKEN',
    RUNNER_REPO_URL: 'https://github.com/owner/project', RUNNER_NAME: 'project-runner', RUNNER_LABELS: 'one,two' };
  const run = () => spawnSync('bash', [join(home, 'entrypoint.sh')], { env, encoding: 'utf8' });
  const first = run(); assert.equal(first.status, 0, first.stderr); assert.equal(first.stdout, 'token=unset\n');
  assert.equal(read(home, 'config-args'), '--unattended\n--replace\n--url\nhttps://github.com/owner/project\n--token\nFAKE_TOKEN\n--name\nproject-runner\n--labels\none,two\n--work\n_work\n');
  rmSync(join(home, 'config.sh')); delete env.RUNNER_TOKEN;
  assert.equal(run().status, 0, 'existing .runner never needs config.sh or token');
  rmSync(join(home, '.runner'));
  const empty = run(); assert.notEqual(empty.status, 0); assert.match(empty.stderr, /first start needs RUNNER_TOKEN/);
});

