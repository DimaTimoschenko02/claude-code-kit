function fakeExecution(pages = [{ runners: [] }]) {
  const calls = [];
  const token = Buffer.from('FAKE_REGISTRATION_TOKEN\n');
  const run = (command, args, options) => {
    calls.push({ command, args, input: options?.input?.toString(), options });
    if (args.includes('--slurp')) return Buffer.from(JSON.stringify(pages));
    if (args.includes('POST')) return token;
    return Buffer.alloc(0);
  };
  return { calls, run, token };
}

