import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { serviceName, validate } from './validate.mjs';

const TEMPLATE = fileURLToPath(new URL('../template/', import.meta.url));
const HEADER = '# generated by claude-code-kit ci-runner from runner.json — edit runner.json and re-render\n';
const PACKAGES = 'ca-certificates curl git jq tar unzip xz-utils openssh-client build-essential python3'.split(' ');
const LOGGING = { driver: 'json-file', options: { 'max-size': '10m', 'max-file': '3' } };

export function load(root) {
  const directory = resolve(root, 'infra', 'ci-runner');
  try {
    return { directory, config: validate(JSON.parse(readFileSync(join(directory, 'runner.json'), 'utf8'))) };
  } catch (error) {
    throw new Error(`${join(directory, 'runner.json')}: ${error.message}`);
  }
}

function limits(value) {
  const result = {};
  const keys = { cpuset: 'cpuset', cpus: 'cpus', cpuShares: 'cpu_shares', mem: 'mem_limit',
    oomScoreAdj: 'oom_score_adj', pids: 'pids_limit', shm: 'shm_size' };
  for (const [key, field] of Object.entries(keys)) if (value[key] !== undefined) result[field] = value[key];
  result.memswap_limit = value.mem;
  return result;
}

function database(db) {
  return {
    image: db.image,
    command: ['postgres', '-p', String(db.port), '-c', 'jit=off', '-c', 'fsync=off', '-c', 'synchronous_commit=off', '-c', 'full_page_writes=off'],
    // An explicit PGDATA works across image majors; their default data directory changed in PostgreSQL 18.
    environment: { POSTGRES_USER: db.user, POSTGRES_DB: db.db, POSTGRES_HOST_AUTH_METHOD: 'trust', PGDATA: '/var/lib/postgresql/ci-data' },
    volumes: ['pgdata:/var/lib/postgresql'],
    ...limits({ cpus: db.cpus, mem: db.mem }), restart: 'unless-stopped', logging: LOGGING,
  };
}

export function compose(config) {
  const services = {};
  const volumes = {};
  if (config.testDb) { services.postgres = database(config.testDb); volumes.pgdata = {}; }
  config.runners.forEach((runner, index) => {
    const name = serviceName(runner, index, config.runners);
    services[name] = {
      build: '.', ...(runner.testDb ? { network_mode: 'service:postgres', depends_on: ['postgres'] } : {}),
      environment: { RUNNER_TOKEN: '${RUNNER_TOKEN:-}', RUNNER_REPO_URL: `https://github.com/${config.repo}`,
        RUNNER_NAME: runner.name, RUNNER_LABELS: runner.labels.join(',') },
      volumes: [`${name}:/home/runner`], ...limits(runner.limits), restart: 'unless-stopped', logging: LOGGING,
    };
    volumes[name] = {};
  });
  return { name: config.composeName, services, volumes };
}

function template(name, values) {
  return readFileSync(join(TEMPLATE, name), 'utf8').replace(/\r\n/g, '\n')
    .replace(/\{\{(\w+)\}\}/g, (_, key) => values[key]);
}

function dockerfile(config) {
  const values = { ...config, packages: [...new Set([...PACKAGES, ...[...(config.extraApt ?? [])].sort()])].join(' '),
    playwright: (config.features ?? []).includes('playwright') ? template('playwright.Dockerfile', config) : '' };
  return template('Dockerfile', values);
}

export function outputs(config) {
  // JSON flow syntax is YAML 1.2: no YAML dependency, ambiguous scalars or platform-specific quoting.
  const reasons = '# CI shares a host: bounded memory without swap keeps its OOM inside CI; CPU limits leave room for production.\n'
    + '# Only named volumes: registration, self-updates, tool caches and workspaces survive rebuilds.\n'
    + '# Chromium renderer buffers need shm_size above Docker\'s 64 MB default.\n'
    + '# A test DB shares loopback with opted-in runners; durability is wasted on disposable test data.\n';
  return {
    'compose.yaml': HEADER + reasons + JSON.stringify(compose(config), null, 2) + '\n',
    Dockerfile: HEADER + dockerfile(config),
    'entrypoint.sh': HEADER + readFileSync(join(TEMPLATE, 'entrypoint.sh'), 'utf8').replace(/\r\n/g, '\n'),
  };
}

export function render(root) {
  const { directory, config } = load(root);
  const files = outputs(config);
  for (const [name, contents] of Object.entries(files)) writeFileSync(join(directory, name), contents);
  return Object.keys(files);
}

export function check(root) {
  const { directory, config } = load(root);
  return Object.entries(outputs(config)).flatMap(([name, contents]) => {
    try { if (readFileSync(join(directory, name), 'utf8') === contents) return []; }
    catch (error) { if (error.code !== 'ENOENT') throw error; }
    return [`${join(directory, name)}: generated output differs or is missing; run ci-runner render`];
  });
}
