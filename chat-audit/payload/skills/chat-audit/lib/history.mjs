// chat-audit :: history — one generated note per lens per project: what the lens found, what was changed for it,
// whether the change worked, and whether the finding came back.
//
// Why (2026-11-26): the token audit ran four times (21.08, 16.09, 28.10, 04.11) and found the same ~190–200k context
// per call each time. The ledger had the claims and the runs log had the lenses, but nothing joined them, so each run
// started blind and re-advised what was already advised — and no fix carried a number that could say it rotted.
//
// Written by `runs.mjs refresh` / `record` into <MIND_VAULT>/01 projects/chat-audit/history/<project>/<lens>.md, never
// by hand. Source: the project's .claude/state/chat-audit/ledger.jsonl — only lines with `lens`.
//
// A return: a later finding on the same lens with the same failure class. The generic form words (missing,
// exists-but-did-not-fire, …) are not a failure class: two findings that share only those are not the same problem.
// A return after an accepted change marks that change rotted, with its lifetime in days — the number behind mandatory
// item 20 «Срок жизни правила». An auditor who saw the return writes it as a finding line (modes/land.md):
// `class:"fix-rotted"`, `class_was`, `rotted_change`, `fix_lived_days` — that link wins over the class match.
// Lines without `lens` (direct edits logged by instructions-tuning) go to one note, «без линзы».
import fs from 'node:fs';
import path from 'node:path';
import { createHash, randomUUID } from 'node:crypto';
import { fmt, measure, readLedger } from './effect.mjs';

const DAY = 86400e3;
export const MARK = '> Generated by runs.mjs from the project ledger, do not edit.';
export const NO_LENS = 'без линзы';
const GENERIC = /^(missing|mixed|fix-rotted|already[- ]solved|exists[- ]but[- ]did[- ]not[- ]fire|exists[- ]but[- ]too[- ]broad|rule (is )?missing|no rule|rule exists and did not fire|rule exists and is too broad)$/;
const APPLIED = new Set(['accepted', 'edited']);

const day = (ts) => new Date(ts).toISOString().slice(0, 10);
// A change line written after the fact says when the change took effect in `applied_at`.
const when = (c) => (Number.isFinite(Date.parse(c.applied_at)) ? c.applied_at : c.ts);
const days = (from, to) => Math.floor((Date.parse(to) - Date.parse(from)) / DAY);
const cell = (s) => String(s ?? '').replace(/\s+/g, ' ').trim();

/** The failure class as a match key, or null when it names only the form of the finding. */
export function classKey(text) {
  const k = cell(text).toLowerCase().replace(/[.;:!]+$/, '');
  return !k || GENERIC.test(k) ? null : k;
}

/** A finding's own failure class: a fix-rotted line keeps the original in `class_was`. */
const findingKey = (f) => classKey(f.class === 'fix-rotted' ? f.class_was : f.class);

/** A lens as a file name: item ids and lens names pass, a slash does not. */
export const lensFile = (lens) => `${String(lens).replace(/[\\/:*?"<>|]/g, '-')}.md`;

/**
 * Ledger rows → per lens: findings, changes (change lines, and accepted findings whose fix has no change line), returns
 * and rotted changes. Pure: `effects` maps a change id to its measured effect.mjs row.
 */
export function lensHistory(rows, effects = new Map()) {
  const byLens = new Map();
  for (const r of rows) {
    if (!r || !Number.isFinite(Date.parse(r.ts))) continue;
    const lens = r.lens == null || r.lens === '' ? NO_LENS : String(r.lens);
    if (!byLens.has(lens)) byLens.set(lens, { findings: [], changes: [] });
    const h = byLens.get(lens);
    if (r.type === 'change') h.changes.push({ ...r, origin: 'line' });
    else h.findings.push({ ...r });
  }
  for (const h of byLens.values()) {
    const byTime = (a, b) => Date.parse(a.ts) - Date.parse(b.ts);
    h.findings.sort(byTime);
    // An accepted fix with no change line of its own is still a change: it can rot.
    for (const f of h.findings) {
      if (!APPLIED.has(f.verdict) || !f.applied) continue;
      const line = h.changes.find((c) => (c.commit && String(f.applied).startsWith(String(c.commit).slice(0, 7)))
        || (c.commit && String(c.commit).startsWith(String(f.applied).slice(0, 7))) || (c.trigger && c.trigger === f.anchor));
      if (line) { f.change = line.id; continue; }
      const id = `F:${String(f.applied).slice(0, 12)}`;
      f.change = id;
      if (!h.changes.some((c) => c.id === id)) {
        h.changes.push({ id, ts: f.ts, class: f.class, paths: [], commit: /^[0-9a-f]{7,40}$/.test(f.applied) ? f.applied : null,
          applied: f.applied, audit: f.audit, origin: 'finding', from: f });
      }
    }
    h.changes.sort((a, b) => Date.parse(when(a)) - Date.parse(when(b)));
    for (const c of h.changes) c.effect = effects.get(c.id) || null;
    // Returns: a later finding of the same class. Same audit is the same report, not a return.
    for (const f of h.findings) {
      const key = findingKey(f);
      const same = (e) => e !== f && e.audit !== f.audit && key && findingKey(e) === key;
      f.returnOf = h.findings.filter((e) => same(e) && Date.parse(e.ts) < Date.parse(f.ts));
      f.cameBack = h.findings.filter((e) => same(e) && Date.parse(e.ts) > Date.parse(f.ts));
    }
  }
  // Rotted: the auditor's fix-rotted line first — it names the change, which may sit under another lens or none — then
  // the first later finding of the same class on the same lens.
  const rot = (c, f, lifetime) => { c.rotted = { at: f.ts, lifetime, finding: f }; };
  const allChanges = [...byLens.values()].flatMap((h) => h.changes);
  for (const f of [...byLens.values()].flatMap((h) => h.findings)) {
    const c = f.rotted_change && allChanges.find((x) => String(x.id) === String(f.rotted_change));
    if (c && !c.rotted) rot(c, f, Number.isFinite(f.fix_lived_days) ? f.fix_lived_days : days(when(c), f.ts));
  }
  for (const h of byLens.values()) {
    for (const f of h.findings) {
      const key = findingKey(f);
      if (!key) continue;
      for (const c of h.changes) {
        if (c.rotted || c.from === f || f.change === c.id || classKey(c.class) !== key) continue;
        if (Date.parse(f.ts) <= Date.parse(when(c)) || (c.audit && c.audit === f.audit) || (c.from && c.from.audit === f.audit)) continue;
        rot(c, f, days(when(c), f.ts));
      }
    }
  }
  return byLens;
}

function effectText(c) {
  const e = c.effect;
  const recorded = c.verdict ? `записан: ${c.verdict}` : '';
  if (e) {
    const one = (x) => {
      const nums = x.before || x.after ? ` — до ${fmt(x.before, x.signal || '')}, после ${fmt(x.after, x.signal || '')}` : '';
      return `${x.verdict}${nums}`;
    };
    const named = (x) => `${String(x.signal).replace(/^metric:/, '')}: ${one(x)}`;
    const text = e.extra?.length ? [e, ...e.extra].map(named).join('; ') : one(e);
    return `${text}${recorded ? ` · ${recorded}` : ''}`;
  }
  if (c.measureError) return `не измерен: ${c.measureError}${recorded ? ` · ${recorded}` : ''}`;
  if (!c.signal) return recorded || (c.origin === 'finding' ? 'не мерили: у правки нет строки change с сигналом' : 'не мерили: сигнала нет');
  return recorded || 'не мерили в этом прогоне (`--no-measure` или нет транскриптов на этой машине)';
}

function signalText(s) {
  if (!s) return 'нет';
  const parts = [s.src, s.want && `want ${s.want}`, s.by && `by ${s.by}`, s.re && !String(s.src).startsWith('metric:') && `re \`${s.re}\``];
  return parts.filter(Boolean).join(' · ');
}

function changeBlock(c) {
  const lines = [`### ${day(when(c))} · правка ${c.id}`];
  lines.push(`- Что: ${cell(c.class) || '—'}`);
  if (c.paths?.length) lines.push(`- Пути: ${c.paths.map((p) => `\`${p}\``).join(', ')}`);
  if (c.applied && !c.commit) lines.push(`- Применено: ${cell(c.applied)}`);
  if (c.commit) lines.push(`- Коммит: \`${String(c.commit).slice(0, 12)}\``);
  if (c.origin === 'line') lines.push(`- Сигнал: ${[c.signal, ...(c.signals_extra || [])].map(signalText).join('; ')}`);
  lines.push(`- Эффект: ${effectText(c)}`);
  if (c.rotted) {
    const back = c.rotted.at ? `вернулась ${day(c.rotted.at)}` : 'отмечена в ledger';
    const life = c.rotted.lifetime != null ? `, жила ${c.rotted.lifetime} дн.` : '';
    lines.push(`- **Сгнила**: ${back}${life}${c.rotted.finding ? ` — «${cell(c.rotted.finding.claim)}»` : ''}`);
  } else {
    lines.push('- Сгнила: нет');
  }
  return lines.join('\n');
}

function findingBlock(f) {
  const lines = [`### ${day(f.ts)} · находка · ${f.verdict || 'без вердикта'}`];
  lines.push(`- Что: ${cell(f.claim) || '—'}`);
  lines.push(`- Класс: ${cell(f.class) || '—'}${f.anchor ? ` · якорь \`${cell(f.anchor)}\`` : ''}${f.audit ? ` · аудит ${f.audit}` : ''}`);
  if (f.applied || f.change) lines.push(`- Правка: ${[f.change, f.applied && f.applied !== f.change ? `\`${cell(f.applied)}\`` : null].filter(Boolean).join(' · ')}`);
  if (f.note) lines.push(`- Заметка: ${cell(f.note)}`);
  if (f.returnOf.length) lines.push(`- Повтор: уже находили ${f.returnOf.map((e) => day(e.ts)).join(', ')}`);
  lines.push(`- Вернулась: ${f.cameBack.length ? f.cameBack.map((e) => day(e.ts)).join(', ') : 'нет'}`);
  return lines.join('\n');
}

/** What the next run of this lens reads first: classes advised more than once, and the last effect of their fixes. */
function repeatsSection(h) {
  const groups = new Map();
  for (const f of h.findings) {
    const key = findingKey(f);
    if (!key) continue;
    if (!groups.has(key)) groups.set(key, { class: cell(f.class === 'fix-rotted' ? f.class_was : f.class), findings: [] });
    groups.get(key).findings.push(f);
  }
  const out = [];
  for (const [key, g] of groups) {
    const audits = new Set(g.findings.map((f) => f.audit || f.ts));
    if (audits.size < 2) continue;
    const fixes = h.changes.filter((c) => classKey(c.class) === key || g.findings.some((f) => f.change === c.id));
    const last = fixes[fixes.length - 1];
    const effect = last ? `последняя правка ${last.id} (${day(when(last))}): ${effectText(last)}${last.rotted ? ', сгнила' : ''}` : 'правок не было';
    out.push(`- «${g.class}» — советовали ${audits.size} раз (${g.findings.map((f) => day(f.ts)).join(', ')}); ${effect}`);
  }
  return out;
}

export function renderNote({ project, lens, title, h, today, created, revision }) {
  const rotted = h.changes.filter((c) => c.rotted);
  const measured = h.changes.filter((c) => c.effect);
  const tally = {};
  measured.forEach((c) => { tally[c.effect.verdict] = (tally[c.effect.verdict] || 0) + 1; });
  const repeats = repeatsSection(h);
  const entries = [...h.findings.map((f) => ({ ts: f.ts, order: 0, text: findingBlock(f) })),
    ...h.changes.map((c) => ({ ts: when(c), order: 1, text: changeBlock(c) }))]
    .sort((a, b) => Date.parse(a.ts) - Date.parse(b.ts) || a.order - b.order);
  return [
    '---', 'kind: note', 'topic: ["[[chat-audit]]"]', `created: ${created}`,
    `description: История линзы ${lens} чат-аудита в проекте ${project}: что находили, что меняли, сработало ли, что вернулось.`,
    '---', '', `# ${project} · ${lens}${title ? ` — ${title}` : ''}`, '', MARK, `<!-- source revision: ${revision} -->`, '',
    `На ${today} (UTC). Находок ${h.findings.length}, правок ${h.changes.length}`
      + `${measured.length ? ` (измерено ${measured.length}: ${Object.entries(tally).map(([k, v]) => `${k} ${v}`).join(' · ')})` : ''}`
      + `, сгнило ${rotted.length}.`, '',
    '## Уже советовали', '', ...(repeats.length ? repeats : ['- Повторов класса нет.']), '',
    '## Сгнившие правки', '',
    ...(rotted.length ? rotted.map((c) => `- ${c.id} (${day(when(c))}): ${c.rotted.lifetime != null ? `${c.rotted.lifetime} дн.` : 'срок не известен'} — ${cell(c.class)}`) : ['- Нет.']),
    '', '## По датам', '', entries.map((e) => e.text).join('\n\n'), '',
  ].join('\n');
}

function replaceFile(file, content) {
  const temp = `${file}.${randomUUID()}.tmp`;
  try {
    fs.writeFileSync(temp, content, 'utf8');
    fs.renameSync(temp, file);
  } finally { fs.rmSync(temp, { force: true }); }
}

/** Effect rows for the lensed change lines with a signal, measured on this machine's transcripts. */
function measureEffects(ledger, rows, now) {
  const ids = rows.filter((r) => r && r.type === 'change' && r.signal).map((r) => r.id);
  const effects = new Map(), errors = new Map();
  if (!ids.length) return { effects, errors };
  const project = path.resolve(path.dirname(ledger), '../../..');
  try {
    for (const e of measure({ project, ledger, ids, now, git: false })) if (e) effects.set(e.id, e);
  } catch (error) {
    // One bad line (an unknown metric, a broken regex) must not hide the whole history: measure one by one.
    for (const id of ids) {
      try { const [e] = measure({ project, ledger, ids: [id], now, git: false }); if (e) effects.set(id, e); }
      catch (inner) { errors.set(id, inner.message); }
    }
  }
  return { effects, errors };
}

/**
 * Regenerate every history note of one project from its ledger. Notes for lenses no longer in the ledger are removed
 * (only generated ones). Returns {written, removed, unlensed}.
 */
export function refreshHistory({ root, notesDir, project, ledger, titles = new Map(), today, now = Date.now(), measureEffects: doMeasure = true }) {
  const raw = fs.readFileSync(ledger, 'utf8');
  const rows = readLedger(ledger).filter(Boolean);
  const { effects, errors } = doMeasure ? measureEffects(ledger, rows, now) : { effects: new Map(), errors: new Map() };
  const byLens = lensHistory(rows, effects);
  for (const h of byLens.values()) for (const c of h.changes) if (errors.has(c.id)) c.measureError = errors.get(c.id);
  const dir = path.join(root, notesDir, 'history', project);
  fs.mkdirSync(dir, { recursive: true });
  const revision = createHash('sha256').update(raw.replaceAll('\r\n', '\n')).digest('hex');
  const written = [];
  for (const [lens, h] of byLens) {
    const file = path.join(dir, lensFile(lens));
    let current = '';
    try { current = fs.readFileSync(file, 'utf8'); } catch { /* new note */ }
    const created = /^created: (\d{4}-\d\d-\d\d)$/m.exec(current.replaceAll('\r\n', '\n'))?.[1] ?? today;
    const next = renderNote({ project, lens, title: titles.get(lens) || '', h, today, created, revision });
    if (current.replaceAll('\r\n', '\n') !== next) replaceFile(file, next);
    written.push(file);
  }
  const removed = [];
  for (const name of fs.readdirSync(dir)) {
    const file = path.join(dir, name);
    if (!name.endsWith('.md') || written.includes(file)) continue;
    if (fs.readFileSync(file, 'utf8').includes(MARK)) { fs.rmSync(file); removed.push(file); }
  }
  const unlensed = rows.filter((r) => r.lens == null || r.lens === '').length;
  return { written, removed, unlensed };
}
